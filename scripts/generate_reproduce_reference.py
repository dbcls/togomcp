#!/usr/bin/env python3
"""Generate the query-provenance workflow's references/reproduce.md from the script.

`scripts/togomcp_reproduce.py` is what a paper's reader runs against a query ledger.
The workflow cannot ship it as a file (get_workflow serves only .md/.yaml/.yml/.txt),
so reproduce.md carries a URL pinned to the release tag that holds this version of
the script, the commands, and a full copy for readers who cannot fetch it.

The URL and the copy must describe the SAME version. If the script changed in a later
release and only the copy were refreshed, the copy would be new and the URL old, and
nothing would notice — so both come from the script itself (`__version__`,
`RELEASED_IN`) and are written together here. tests/test_reproduce_reference_in_sync.py
fails on drift.

Usage:
    python scripts/generate_reproduce_reference.py           # rewrite reproduce.md
    python scripts/generate_reproduce_reference.py --check   # exit 1 if it is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPT = REPO_ROOT / "scripts" / "togomcp_reproduce.py"
OUTPUT = (
    REPO_ROOT / "togo_mcp" / "data" / "skills" / "public" / "query-provenance"
    / "references" / "reproduce.md"
)
REPO_URL = "https://github.com/dbcls/togomcp"
RAW_URL = "https://raw.githubusercontent.com/dbcls/togomcp"


def _constant(source: str, name: str) -> str:
    m = re.search(rf'^{name} = "([^"]+)"$', source, re.M)
    if not m:
        raise SystemExit(f"{SCRIPT.name}: no `{name} = \"...\"` line")
    return m.group(1)


def build() -> str:
    source = SCRIPT.read_text(encoding="utf-8")
    version = _constant(source, "__version__")
    tag = _constant(source, "RELEASED_IN")
    raw = f"{RAW_URL}/{tag}/scripts/{SCRIPT.name}"
    blob = f"{REPO_URL}/blob/{tag}/scripts/{SCRIPT.name}"
    # Four backticks: the copy must survive any fence inside the script.
    return f"""<!-- GENERATED by scripts/generate_reproduce_reference.py — do not edit by hand. -->
# Re-running a query ledger: `togomcp_reproduce.py` {version}

This is the script a reader (or the author, later) runs to re-execute a
`ledger.yaml` and compare the results with what was recorded. **In a session, do
not run it, rewrite it or write a replacement** — check by re-calling the tools
(SKILL.md step 3). Put the URL and commands below into `PROVENANCE.md`.

- Script version: **{version}**, released in TogoMCP **{tag}**
- Pinned URL (this exact version): {blob}
- Raw file: {raw}

## Commands

Requires [uv](https://docs.astral.sh/uv/); it installs the dependencies
(`httpx`, `pyyaml`, `fastmcp`) declared inside the script.

```bash
# run the pinned version directly
uv run {raw} ledger.yaml

# or download it first
curl -LO {raw}
uv run togomcp_reproduce.py ledger.yaml

# machine-readable results
uv run togomcp_reproduce.py ledger.yaml --json

# write a copy of the ledger with result_sha256 filled in for matching calls
uv run togomcp_reproduce.py ledger.yaml --write-ledger ledger.hashed.yaml
```

## What it does

- `run_sparql` calls are POSTed **directly** to the recorded `endpoint_url`, not
  through TogoMCP, so they still run if the server changes or is gone.
- Other tools are replayed over MCP against `togomcp.server_url` (a `local` ledger
  is replayed against the public server; `--server-url` overrides). The server's
  version is printed.
- `evidence` and `lookup` calls are run; `diagnostic` calls are skipped. A `lookup`
  mismatch is a warning only.

Exit codes: `0` every evidence call matched; `1` an evidence call mismatched or was
recorded wrongly (`ledger_error`); `2` some evidence call could not be run
(`endpoint_error` — retry later); `3` the ledger could not be read.

## Full copy of the script

````python
{source.rstrip()}
````
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if reproduce.md is stale")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(REPO_ROOT)} is stale; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
