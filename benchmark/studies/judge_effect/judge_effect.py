#!/usr/bin/env python3
"""Separate the judge change from the system change in the paper's 2.1 re-evaluation.

The frozen paper results (benchmark/results-Kinjo2026/, read only) hold, per condition:

    A  rev0 answers (2026-02-28 / 03-01) judged by Opus 4.6   x5
    B  rev0 answers                      judged by Opus 4.7   x5
    C  2026-05-04 answers                judged by Opus 4.7   x5

so, per arm (TogoMCP, no-tool baseline) and per question (mean of the 5 judge runs):

    judge effect   B - A   same answers, judge changed
    system effect  C - B   same judge, answers re-collected (TogoMCP, MIEs, data changed)
    total          C - A   what a naive rev0 -> paper comparison shows

The no-tool arm is the control: it never touches TogoMCP, so its C - B is run-to-run answer
variation plus any question/reference edits, not system improvement.

The judge sees question and ideal_answer, both of which were edited in the maintained question
set between batches, so every number is reported on all questions and on the subset whose
question AND ideal_answer text are identical in both batches. Content-policy refusals
(answers carrying the API refusal text) are excluded and counted.

Usage:  python judge_effect.py [--out FINDINGS.md]
"""
from __future__ import annotations

import argparse
import csv
import math
import re
import statistics as st
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
FROZEN = HERE.parents[1] / "results-Kinjo2026"
CONDITIONS = {  # condition -> (rev0 date)
    "with_guide": "2026-02-28", "ng1": "2026-03-01", "ng2": "2026-03-01", "no_mie": "2026-02-28",
}
REFUSAL_RE = re.compile(r"violate our Usage Policy|unable to respond to this request", re.I)


def load(pattern: str):
    """question_id -> {'scores': {arm: [5 scores]}, 'question', 'ideal', 'refusals': {arm: n}}"""
    files = sorted(FROZEN.glob(pattern))
    assert len(files) == 5, f"{pattern}: expected 5 judge runs, found {len(files)}"
    out = defaultdict(lambda: {"scores": defaultdict(list), "refusals": defaultdict(int)})
    for f in files:
        with f.open(encoding="utf-8") as fh:
            for r in csv.DictReader(fh):
                d = out[r["question_id"]]
                d["question"], d["ideal"] = r["question"].strip(), r["ideal_answer"].strip()
                for arm in ("togomcp", "baseline"):
                    if REFUSAL_RE.search(r.get(f"{arm}_answer") or ""):
                        d["refusals"][arm] += 1
                        continue
                    try:
                        s = float(r[f"{arm}_total_score"])
                    except (KeyError, ValueError):
                        continue
                    if s > 0:  # 0 = failed-judge sentinel
                        d["scores"][arm].append(s)
    return out


def qmean(cell, q, arm):
    v = cell[q]["scores"][arm]
    return st.mean(v) if v else None


def paired(x_cell, y_cell, qs, arm):
    """mean over questions of (y - x), 95% CI, n"""
    d = [qmean(y_cell, q, arm) - qmean(x_cell, q, arm) for q in qs
         if qmean(y_cell, q, arm) is not None and qmean(x_cell, q, arm) is not None]
    if len(d) < 2:
        return None, None, len(d)
    return st.mean(d), 1.96 * st.stdev(d) / math.sqrt(len(d)), len(d)


def level(cell, qs, arm):
    v = [qmean(cell, q, arm) for q in qs if qmean(cell, q, arm) is not None]
    return st.mean(v) if v else None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default=str(HERE / "FINDINGS.md"))
    args = ap.parse_args()

    f = lambda v: f"{v:.2f}" if v is not None else "n/a"
    fd = lambda m, ci: f"{m:+.2f} ± {ci:.2f}" if m is not None else "n/a"
    L = ["# Judge effect vs system effect in the 2.1 re-evaluation", "",
         "Generated by `judge_effect.py` from the frozen `benchmark/results-Kinjo2026/` "
         "(read only). Scores are totals on the 4 to 20 scale; each question's score is the "
         "mean of 5 judge runs; differences are paired by question, with 95% CIs "
         "(1.96 × SE). A = rev0 answers × Opus 4.6, B = rev0 answers × Opus 4.7, "
         "C = 2026-05-04 answers × Opus 4.7.", ""]
    summary = []
    for cond, rdate in CONDITIONS.items():
        A = load(f"rev0/{cond}-{rdate}-Opus4.6-v*.csv")
        B = load(f"rev0/{cond}-{rdate}-Opus4.7-v*.csv")
        C = load(f"{cond}-2026-05-04-Opus4.7-v*.csv")
        allq = sorted(set(A) & set(B) & set(C))
        same = [q for q in allq if A[q]["question"] == C[q]["question"] and A[q]["ideal"] == C[q]["ideal"]]
        L += [f"## {cond}", "",
              f"{len(allq)} questions in all three cells; {len(same)} with identical question and "
              f"ideal answer in both batches.", "",
              "| Arm | Subset | A (rev0×4.6) | B (rev0×4.7) | C (05-04×4.7) | Judge B−A | System C−B | Total C−A |",
              "|---|---|---:|---:|---:|---:|---:|---:|"]
        for arm, name in (("togomcp", "TogoMCP"), ("baseline", "No-tool")):
            for label, qs in (("all", allq), ("unchanged", same)):
                j = paired(A, B, qs, arm)
                s = paired(B, C, qs, arm)
                t = paired(A, C, qs, arm)
                L.append(f"| {name} | {label} (n={len(qs)}) | {f(level(A, qs, arm))} | "
                         f"{f(level(B, qs, arm))} | {f(level(C, qs, arm))} | {fd(j[0], j[1])} | "
                         f"{fd(s[0], s[1])} | {fd(t[0], t[1])} |")
                if label == "all":
                    summary.append((cond, name, j[0], s[0], t[0]))
        # the paper's effect size: TogoMCP minus no-tool, per cell
        L += ["", "TogoMCP − no-tool Δ per cell (all questions):", "",
              "| Cell | Δ |", "|---|---:|"]
        for nm, cell in (("A rev0×4.6", A), ("B rev0×4.7", B), ("C 05-04×4.7", C)):
            d = [qmean(cell, q, "togomcp") - qmean(cell, q, "baseline") for q in allq
                 if qmean(cell, q, "togomcp") is not None and qmean(cell, q, "baseline") is not None]
            L.append(f"| {nm} | {st.mean(d):+.2f} (n={len(d)}) |")
        ref = {k: sum(cell[q]["refusals"][arm] for q in cell for arm in ("togomcp", "baseline"))
               for k, cell in (("A", A), ("B", B), ("C", C))}
        L += ["", f"Refusal cells excluded (both arms, 5 runs each): A {ref['A']}, B {ref['B']}, "
              f"C {ref['C']}.", ""]
    L += ["## Summary (all questions)", "",
          "| Condition | Arm | Judge effect | System effect | Total |", "|---|---|---:|---:|---:|"]
    L += [f"| {c} | {a} | {j:+.2f} | {s:+.2f} | {t:+.2f} |" for c, a, j, s, t in summary]
    by = {(c, a): (j, s, t) for c, a, j, s, t in summary}
    L += ["", "Net system effect = TogoMCP system effect minus the no-tool control's (C−B), i.e. "
          "the change in the TogoMCP − no-tool Δ under the same judge:", "",
          "| Condition | Net system effect | Judge effect on Δ (TogoMCP − no-tool, B−A) |",
          "|---|---:|---:|"]
    for c in CONDITIONS:
        (jt, st_, _), (jb, sb, _) = by[(c, "TogoMCP")], by[(c, "No-tool")]
        L.append(f"| {c} | {st_ - sb:+.2f} | {jt - jb:+.2f} |")
    (jt, st_, tt), (jb, sb, tb) = by[("with_guide", "TogoMCP")], by[("with_guide", "No-tool")]
    L += ["", "## Reading", "",
          f"- The judge change (Opus 4.6 to 4.7) raised both arms by a similar amount (With Guide: "
          f"TogoMCP {jt:+.2f}, no-tool {jb:+.2f}), so it leaves the TogoMCP − no-tool Δ almost "
          f"unchanged ({jt - jb:+.2f}). It inflates absolute scores, not the effect size.",
          f"- The no-tool baseline's rise from rev0 to the paper batch (With Guide {tb:+.2f}) is "
          f"mostly the judge ({jb:+.2f}); the rest ({sb:+.2f}) is run-to-run answer variation, "
          f"since that arm never uses TogoMCP.",
          f"- The system improvement between the batches is the TogoMCP arm's gain beyond that "
          f"control: With Guide {st_ - sb:+.2f} points (TogoMCP {st_:+.2f} vs no-tool {sb:+.2f} "
          f"under the same judge). A naive rev0 to paper comparison of the TogoMCP arm "
          f"({tt:+.2f}) would overstate it by about {tt - (st_ - sb):.1f} points.",
          "- The judge change leaves the Δ nearly unchanged for with_guide, ng1 and ng2 "
          f"({by[('with_guide','TogoMCP')][0]-by[('with_guide','No-tool')][0]:+.2f}, "
          f"{by[('ng1','TogoMCP')][0]-by[('ng1','No-tool')][0]:+.2f}, "
          f"{by[('ng2','TogoMCP')][0]-by[('ng2','No-tool')][0]:+.2f}) but not for no_mie "
          f"({by[('no_mie','TogoMCP')][0]-by[('no_mie','No-tool')][0]:+.2f}): Opus 4.7 scores "
          "no-MIE TogoMCP answers relatively higher than 4.6 did. Comparisons involving no_mie "
          "across judges need that correction; within one judge they are unaffected.",
          "- no_mie also has the largest net system effect between the batches.",
          "- Questions and ideal answers are textually identical in both batches for every "
          "condition, so question edits do not confound these differences."]
    Path(args.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[-(len(summary) + 3):]))
    print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
